from cg_iplattice import ip_roundup  # noqa: E402


def make_sep2d(nm, area, root_pool, root_types, tl_price=10.0, workers=1, log=print):
    inst = C.Inst(nm, area)
    state = dict(types=None, cols=[], seen=set())
    rng = random.Random(7)

    def setup(types):
        if state['types'] == types:
            return
        state['types'] = types
        raw = inst.raw_bins
        inst.types = [(W, H, c, next(r for r, b in enumerate(raw) if tuple(b) == (W, H, c))) for (W, H, c) in types]
        inst.fit = [[i for i, (w, h) in enumerate(inst.items) if w <= W and h <= H] for (W, H, c, r) in inst.types]
        inst.maxcard = []
        for t, (W, H, c, r) in enumerate(inst.types):
            acc = 0; k = 0
            for v in sorted(inst.areas[i] for i in inst.fit[t]):
                if acc + v > W * H:
                    break
                acc += v; k += 1
            inst.maxcard.append(k)
        for (tn, S, plc) in root_pool:     # a placement valid in a WxH bin is valid in any larger bin
            Wn, Hn = root_types[tn][0], root_types[tn][1]
            for u, (W, H, c, r) in enumerate(inst.types):
                if W >= Wn and H >= Hn and (u, S) not in state['seen']:
                    state['seen'].add((u, S)); state['cols'].append((u, S, plc))

    def sep(types, items, fits, nstar, tl):
        setup(types)
        t0 = time.time(); n = inst.n; T = len(inst.types)
        lp = pywraplp.Solver.CreateSolver('GLOP')
        cov = [lp.Constraint(1, lp.infinity()) for _ in range(n)]
        cnt = [lp.Constraint(-lp.infinity(), float(nstar[t])) for t in range(T)]
        obj = lp.Objective(); obj.SetMinimization()
        for i in range(n):
            u = lp.NumVar(0, lp.infinity(), ''); cov[i].SetCoefficient(u, 1); obj.SetCoefficient(u, 1.0)

        def addvar(t, S):
            v = lp.NumVar(0, lp.infinity(), '')
            for i in S:
                cov[i].SetCoefficient(v, 1)
            cnt[t].SetCoefficient(v, 1)
        for (t, S, plc) in state['cols']:
            if nstar[t] > 0:
                addvar(t, S)

        def add_col(t, plc):
            S = frozenset(i for (i, x, y) in plc)
            if not S or (t, S) in state['seen']:
                return False
            state['seen'].add((t, S)); state['cols'].append((t, S, tuple(plc)))
            if nstar[t] > 0:
                addvar(t, S)
            return True
        it = 0
        while True:
            it += 1
            st = lp.Solve()
            if st != pywraplp.Solver.OPTIMAL:
                return None
            pi = np.array([min(1.0, max(0.0, r.dual_value())) for r in cov])
            mu = [max(0.0, -r.dual_value()) for r in cnt]
            zval = lp.Objective().Value()
            if zval <= 1e-7:
                log(f'      sep: n* fractionally feasible (LP=0) after {it} its, {time.time() - t0:.1f}s')
                return None
            thr = [mu[t] if nstar[t] > 0 else None for t in range(T)]
            if time.time() - t0 < tl and C.heur_price(inst, pi, pi, add_col, rng, n_rand=1, thr=thr):
                continue
            # exact phase: proven bounds for every type, columns for types with n*_t > 0
            s = C.scale_for(pi); w = np.floor(pi * s).astype(np.int64)
            coef = []; found = 0
            for t in range(T):
                dpw, _ = C.dp_bound(inst, t, w)
                Pw = dpw
                base = int(math.floor(mu[t] * s)) if nstar[t] > 0 else -1
                if dpw > base and time.time() - t0 < tl:
                    tlp = tl_price if nstar[t] > 0 else min(2.0, tl_price)
                    sols, ubw = C.cp_price(inst, t, pi, s, w, min(tlp, max(0.5, tl - (time.time() - t0))),
                                           workers, thr_w=base)
                    if ubw is not None:
                        Pw = min(Pw, ubw)
                    if nstar[t] > 0:
                        for plc in sols:
                            if sum(pi[i] for (i, x, y) in plc) > mu[t] + 1e-9:
                                found += add_col(t, plc)
                coef.append(int(Pw) + inst.maxcard[t])
            rhs = int(w.sum())
            lhs = sum(coef[t] * nstar[t] for t in range(T))
            if lhs < rhs:
                log(f'      sep: cut found (LP={zval:.4f}, viol={(rhs - lhs) / s:.4f}) after {it} its, {time.time() - t0:.1f}s')
                return coef, rhs, [int(v) for v in w]
            if not found or time.time() - t0 > tl:
                log(f'      sep: no violated cut (LP={zval:.4f}, found={found}) after {it} its, {time.time() - t0:.1f}s')
                return None
    return sep


def make_checker(nm, area, workers=1, cap_tl=30.0):
    """exact check: can all items be packed into <= nstar[t] bins of each type t?  CP-SAT, fixed slots.
    Symmetry breaking (valid): items ranked by non-increasing area; slot k of a type only takes items of
    rank >= k (sort the used bins of a type by smallest rank: the k-th one has smallest rank >= k)."""
    from ortools.sat.python import cp_model
    raw, items = C.io.read(nm, area)
    order = sorted(range(len(items)), key=lambda i: (-items[i][0] * items[i][1], i))
    rank = {i: k for k, i in enumerate(order)}

    def check(types, nstar, tl):
        m = cp_model.CpModel(); assign = {i: [] for i in range(len(items))}; slots = []
        for t, (W, H, c) in enumerate(types):
            r = next(q for q, b in enumerate(raw) if tuple(b) == (W, H, c))
            for k in range(nstar[t]):
                xi = []; yi = []; ar = []; recs = []
                for i, (w, h) in enumerate(items):
                    if w > W or h > H or rank[i] < k:
                        continue
                    a = m.NewBoolVar(''); xv = m.NewIntVar(0, W - w, ''); yv = m.NewIntVar(0, H - h, '')
                    xi.append(m.NewOptionalFixedSizeIntervalVar(xv, w, a, ''))
                    yi.append(m.NewOptionalFixedSizeIntervalVar(yv, h, a, ''))
                    ar.append(w * h * a); recs.append((i, a, xv, yv)); assign[i].append(a)
                if recs:
                    m.AddNoOverlap2D(xi, yi)
                    m.Add(sum(ar) <= W * H)
                    m.AddCumulative(xi, [items[i][1] for (i, _, _, _) in recs], H)
                    m.AddCumulative(yi, [items[i][0] for (i, _, _, _) in recs], W)
                slots.append((r, k, recs))
        for i in range(len(items)):
            m.AddExactlyOne(assign[i])
        sv = cp_model.CpSolver(); sv.parameters.max_time_in_seconds = min(cap_tl, tl)
        sv.parameters.num_workers = workers
        st = sv.Solve(m)
        if st == cp_model.INFEASIBLE:
            return 'infeasible', None
        if st in (cp_model.FEASIBLE, cp_model.OPTIMAL):
            place = []
            for (r, k, recs) in slots:
                for (i, a, xv, yv) in recs:
                    if sv.Value(a):
                        place.append([r, k, items[i][0], items[i][1], sv.Value(xv), sv.Value(yv)])
            return 'feasible', place
        return 'unknown', None
    return check


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--variant', choices=['weighted', 'area'], default='weighted')
    ap.add_argument('--time', type=float, default=300.0, help='Benders loop time (s)')
    ap.add_argument('--cg-time', type=float, default=30.0)
    ap.add_argument('--sep-price-time', type=float, default=10.0)
    ap.add_argument('--workers', type=int, default=1)
    ap.add_argument('--check-time', type=float, default=20.0, help='exact fixed-count check per n* (0 = off)')
    ap.add_argument('--no-ledger', action='store_true')
    ap.add_argument('--out', default=os.path.join(ROOT, 'results', 'cg', 'bendex.jsonl'))
    ap.add_argument('--stop-at', default=None, help='local HH:MM: no new instance after it; loop time cut to fit')
    ap.add_argument('names', nargs='+')
    a = ap.parse_args()
    stop_ts = None
    if a.stop_at:
        hh, mm = map(int, a.stop_at.split(':'))
        lt = time.localtime(); base = time.mktime((lt.tm_year, lt.tm_mon, lt.tm_mday, hh, mm, 0, 0, 0, -1))
        stop_ts = base if base > time.time() - 6 * 3600 else base + 86400
        if stop_ts - time.time() > 12 * 3600:
            stop_ts -= 86400
    for nm in a.names:
        if stop_ts is not None:
            left = stop_ts - time.time()
            if left < 45:
                print('stop-at reached; skipping', nm, flush=True); break
            a.time = min(a.time, max(5.0, left - a.cg_time - 15))
        T0 = time.time()
        inst = C.Inst(nm, a.variant == 'area')
        lbA, zA, itA, convA, piA = C.phase_a(inst, 6.0)
        res, pool, M = C.run(inst, tl=a.cg_time, workers=a.workers, pi0=piA, lb0=lbA, log=lambda s: None)
        real = max(res['lb'], lbA)
        base_lb = max(C.lattice_roundup(real, inst.all_costs),
                      ip_roundup(nm, inst.area, real, pis=[piA, res['piB']]) or 0)
        print(f'{nm} {a.variant}: root real LB {real:.3f} (conv={res["converged"]}), IP-rounded {base_lb}', flush=True)
        sep = make_sep2d(nm, inst.area, pool, inst.types, tl_price=a.sep_price_time, workers=a.workers,
                         log=lambda s: print(s, flush=True))
        info = {}
        bst = ledger.best().get((nm, a.variant), {})
        ub = bst.get('ub') if bst.get('ub_checked') else None
        chk = make_checker(nm, inst.area, a.workers, a.check_time) if a.check_time > 0 else None
        lb = ip_roundup(nm, inst.area, real, ub_cap=ub, pis=[piA, res['piB']], benders=a.time, info=info,
                        separator=sep, log=lambda s: print(s, flush=True), checker=chk)
        lb = max(lb or 0, base_lb)
        certrel = ''
        if info.get('cert'):  # the final IP (cuts with their integer weights, no-goods) for offline re-checks
            certrel = os.path.join('results', 'cg', 'certs', f"{nm}_{a.variant}_bendex_{time.strftime('%Y%m%dT%H%M%S')}.json")
            os.makedirs(os.path.dirname(os.path.join(ROOT, certrel)), exist_ok=True)
            json.dump(dict(info['cert'], lb=lb, base_lb=base_lb, real=real,
                           piA=None if piA is None else [float(v) for v in piA],
                           piB=None if res['piB'] is None else [float(v) for v in res['piB']]),
                      open(os.path.join(ROOT, certrel), 'w'))
        own_ub = None; solrel = ''; checked = 0
        if info.get('packing'):
            bins_raw, _ = C.io.read(nm, inst.area)
            pcost = sum(bins_raw[t][2] for t, k in {(p[0], p[1]) for p in info['packing']})
            solrel = ledger.sol_relpath(nm, a.variant, 'cg_v2_bendex', pcost)
            json.dump(dict(name=nm, variant=a.variant, method='cg_v2_bendex', cost=pcost, place=info['packing']),
                      open(os.path.join(ROOT, solrel), 'w'))
            cv = C.check(nm, os.path.join(ROOT, solrel), a.variant)
            if cv is not None and cv != pcost:
                print(f'  !! packing cost {pcost} but checker says {cv}', flush=True); cv = None
            if cv is not None:
                own_ub = cv; checked = 1
                if cv < lb:
                    print(f'  !!! checked packing cost {cv} < LB {lb} -- BUG', flush=True)
            if ub is None or (own_ub is not None and own_ub < ub):
                ub = own_ub
        out = dict(name=nm, variant=a.variant, lb_root=base_lb, lb=lb, cuts=info.get('benders_cuts'),
                   nogoods=info.get('nogoods', 0), own_ub=own_ub,
                   best_checked_ub=ub, time=round(time.time() - T0, 1), threads=a.workers, real=real,
                   converged=res['converged'], cert=certrel)
        print(json.dumps(out), flush=True)
        if ub is not None and lb > ub:
            print('  !!! LB > checked UB -- BUG, not recording', flush=True)
            continue
        with open(a.out, 'a') as f:
            f.write(json.dumps(out) + '\n')
        if not a.no_ledger:
            ledger.record(nm, a.variant, 'cg_v2_bendex',
                          'OPTIMAL' if (own_ub is not None and own_ub == lb) else 'LB_ONLY' if own_ub is None else 'FEASIBLE',
                          lb=lb, ub=own_ub, sol_file=solrel if checked else '', checked=checked,
                          time_s=out['time'], threads=a.workers,
                          note=f"root IP-rounded {base_lb}; 2D Benders count cuts={info.get('benders_cuts')}; cert={certrel}"
                               + (' closes_vs_best_checked_ub' if ub is not None and lb == ub else ''))


if __name__ == '__main__':
    main()
