"""cg_bendex: root CG + integer type-count IP with 2D Benders feasibility cuts (track cg, 2026-10-14).

LB = min { sum_t c_t n_t : n integer, constraints (1)-(5) of cg_iplattice.py, plus 2D cuts }.
A 2D cut is an instance of cut (5) of cg_iplattice.py: for ANY pi >= 0,
      sum_t P_t n_t >= sum_i pi_i      (each item lies in exactly one bin; a bin of type t holds a
                                        2D-packable set S, so pi(S) <= P_t)
with P_t a PROVEN upper bound of max{pi(S): S 2D-packable in t}.  In integers: w_i = floor(pi_i*s),
P^w_t = proven bound on max w(S) (min of the area-DP bound and the CP-SAT bound: INFEASIBLE with side
constraint w(S) >= base+1 -> base; FEASIBLE/OPTIMAL -> max(base, BestObjectiveBound); UNKNOWN unused)
plus maxcard_t;  cut  sum_t P^w_t n_t >= sum_i w_i.
pi comes from the separation LP for the current IP minimiser n*:
      min sum_i u_i  s.t.  sum_{p ni i} lam_p + u_i >= 1,  sum_{p of type t} lam_p <= n*_t,  lam, u >= 0
(columns = 2D-packable (t, S), generated by maxrects heuristic + exact CP-SAT pricing).  The cut is
added only if it is violated by n* (checked in exact integer arithmetic).  Whatever pi is used, the
cut is valid, so every OPTIMAL IP value along the loop is a valid lower bound.  If no violated cut
is found, the loop stops (n* is fractionally 2D-feasible, or pricing could not be proven in time).

usage: python src/cg_bendex.py --variant weighted --time 300 MB_C7_11
"""
import argparse
import json
import math
import os
import random
import sys
import time

import numpy as np
from ortools.linear_solver import pywraplp

SRC = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(SRC)
sys.path.insert(0, SRC)
import cg_v2 as C  # noqa: E402
